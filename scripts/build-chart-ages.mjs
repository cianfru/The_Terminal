// Generates src/chart-ages.js — when each chart id FIRST appeared in src/charts-catalog.js, read
// from git history. That makes the "New" rail a reproducible fact rather than an editorial claim.
//
// Runs in `npm run build`. The output is COMMITTED (same convention as src/docs-content.js) because
// CI checks out shallow (actions/checkout fetch-depth 1), where history can't be read — there the
// script leaves the committed file alone rather than emitting a wrong answer.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const OUT = new URL("../src/chart-ages.js", import.meta.url);
const git = (...a) => execFileSync("git", a, { encoding: "utf8" }).trim();

let shallow = "true";
try { shallow = git("rev-parse", "--is-shallow-repository"); } catch { shallow = "true"; }
if (shallow !== "false") {
  console.log("build-chart-ages: shallow or non-git checkout — keeping the committed src/chart-ages.js");
  process.exit(0);
}

// Take the ids from the catalog's OWN export, not a regex — METHOD_FAMILIES also carries `id:`
// fields ("01", "02"…) and a regex happily dated those as charts.
const { CHART_META } = await import(new URL("../src/charts-catalog.js", import.meta.url));
const ids = Object.keys(CHART_META);
const ages = {};
for (const id of ids) {
  try {
    // -S counts occurrences of the string across revisions; the LAST line is the commit that
    // introduced it. Quote the id so "risk" can't match "riskheat".
    const out = git("log", "--diff-filter=AM", `-S"${id}"`, "--format=%ad", "--date=short", "--", "src/charts-catalog.js");
    const first = out.split("\n").filter(Boolean).pop();
    if (first) ages[id] = first;
  } catch { /* a chart with no history yet — skip it rather than guess */ }
}
const body = Object.entries(ages).sort(([a], [b]) => a.localeCompare(b))
  .map(([id, d]) => `  ${/^[a-z][a-z0-9]*$/i.test(id) ? id : JSON.stringify(id)}: "${d}",`).join("\n");
writeFileSync(OUT, `// GENERATED by scripts/build-chart-ages.mjs — do not hand-edit.\n`
  + `// When each chart id first landed in src/charts-catalog.js, per git. Drives the "New" rail.\n`
  + `export const CHART_AGES = {\n${body}\n};\n`);
console.log(`build-chart-ages: dated ${Object.keys(ages).length}/${ids.length} charts`);
